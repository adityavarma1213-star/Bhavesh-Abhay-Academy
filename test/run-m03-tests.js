const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const c = { window: {}, localStorage: { getItem(){ return null; }, setItem(){}, removeItem(){} } };
vm.createContext(c);
vm.runInContext(fs.readFileSync('js/baa-hybrid-mode.js','utf8'), c);
const api = c.window.BAAHybridMode;
assert.ok(api);
const composed = api.compose({steps:[{id:'ai1',title:'Algebra',minutes:20,type:'learn'}]}, {steps:[{id:'c1',title:'Practice Algebra',minutes:15,type:'practice'}]});
assert.equal(composed.mode, 'hybrid');
assert.equal(composed.steps.length, 2);
assert.equal(api.cleanPriority('student'), 'student');
assert.equal(api.cleanPriority('invalid'), 'balanced');
assert.equal(typeof api.loadServer, 'function');
assert.equal(typeof api.saveServer, 'function');
assert.equal(typeof api.clearServer, 'function');
const endpoint = fs.readFileSync('api/m03-hybrid-mode.js','utf8');
assert(endpoint.includes('requireLearnerAccess'));
assert(endpoint.includes('hybrid_learning_paths'));
assert(endpoint.includes('INVALID_HYBRID_PATH'));
assert(endpoint.includes("req.method === 'PUT'"));
assert(endpoint.includes("req.method === 'DELETE'"));
const migration = fs.readFileSync('db/migrations/024_m03_hybrid_mode.sql','utf8');
assert(migration.includes('hybrid_learning_paths'));
console.log('M03 PASS — hybrid composition, priority validation, client/server persistence contract');
