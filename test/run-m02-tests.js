const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const c = { window: {}, localStorage: { getItem(){ return null; }, setItem(){}, removeItem(){} } };
vm.createContext(c);
vm.runInContext(fs.readFileSync('js/baa-custom-mode.js','utf8'), c);
const api = c.window.BAACustomMode;
assert.ok(api);
assert.equal(api.validateStep({title:' Algebra ',minutes:20,type:'practice'}).ok, true);
assert.equal(api.validateStep({title:'x',minutes:2,type:'practice'}).ok, false);
const path = api.normalizePath({schemaVersion:1,mode:'custom',steps:[{id:'a',title:'Algebra',minutes:20,type:'practice',completed:false}]});
assert.equal(path.steps.length,1);
const endpoint = fs.readFileSync('api/m02-custom-mode.js','utf8');
assert(endpoint.includes('requireLearnerAccess'));
assert(endpoint.includes('custom_learning_paths'));
assert(endpoint.includes('INVALID_CUSTOM_PATH'));
assert(endpoint.includes('ON CONFLICT(learner_id)'));
const migration = fs.readFileSync('db/migrations/023_m02_custom_mode.sql','utf8');
assert(migration.includes('custom_learning_paths'));
assert(migration.includes('learner_id TEXT PRIMARY KEY'));
console.log('M02 PASS — bounded custom path validation, server persistence, ownership contract');
