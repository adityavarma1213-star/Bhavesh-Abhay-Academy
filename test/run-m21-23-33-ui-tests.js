#!/usr/bin/env node
const fs=require('fs'),assert=require('assert'),vm=require('vm');

class FakeElement{
  constructor(tag){this.tagName=tag.toUpperCase();this.children=[];this.listeners={};this.attributes={};this.value='';this.textContent='';this.className='';this.firstChild=null;}
  set id(v){this._id=v;if(this._doc)this._doc.nodes[v]=this;}
  get id(){return this._id;}
  append(...nodes){nodes.forEach(n=>{this.children.push(n);if(!this.firstChild)this.firstChild=n;if(n&&n._doc===null)n._doc=this._doc;});}
  appendChild(n){this.append(n);return n;}
  prepend(n){this.children.unshift(n);this.firstChild=this.children[0];}
  removeChild(n){const i=this.children.indexOf(n);if(i>=0)this.children.splice(i,1);this.firstChild=this.children[0]||null;}
  addEventListener(type,fn){(this.listeners[type] ||= []).push(fn);}
  click(){(this.listeners.click||[]).forEach(fn=>fn({target:this}));}
  setAttribute(k,v){this.attributes[k]=String(v);}
  dispatchEvent(e){(this.listeners[e.type]||[]).forEach(fn=>fn(e));}
}
class FakeDocument{
  constructor(){this.nodes={};}
  getElementById(id){return this.nodes[id]||null;}
  createElement(tag){const e=new FakeElement(tag);e._doc=this;return e;}
  add(id,tag='div'){const e=this.createElement(tag);e.id=id;return e;}
}
