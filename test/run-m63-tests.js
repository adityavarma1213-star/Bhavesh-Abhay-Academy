#!/usr/bin/env node
const fs=require('fs'),assert=require('assert'),vm=require('vm');
const catalogue=fs.readFileSync('js/baa-guide-catalogue.js','utf8');
assert.ok(catalogue.includes('BAAGuideCatalogue'));
assert.ok(catalogue.includes("loadScript('js/baa-guide-robot.js','data-baa-m63-robot')"),'catalogue must bootstrap the Guide Robot');
assert.ok(catalogue.includes("loadStyle('css/baa-guide-robot.css','data-baa-m63-style')"),'catalogue must bootstrap Guide Robot styles');
assert.ok(catalogue.includes('data-baa-m63-robot'),'Guide Robot loader must be idempotently tagged');
assert.ok(catalogue.includes('data-baa-m63-style'),'Guide Robot style loader must be idempotently tagged');
const ctx={window:{},document:{readyState:'complete',head:{appendChild(){}},querySelector(){return null}}};vm.createContext(ctx);vm.runInContext(catalogue,ctx);
assert.ok(ctx.window.BAAGuideCatalogue);
const features=ctx.window.BAAGuideCatalogue.getFeatures();
assert.ok(features.length>=10,'catalogue should cover the major BAA features');
assert.ok(features.some(f=>f.id==='student-os'));
assert.ok(features.some(f=>f.id==='teacher-portal'));
assert.ok(features.some(f=>f.id==='parent-os'));
assert.ok(features.some(f=>f.id==='themes'));
assert.ok(features.every(f=>f.id&&f.title&&f.description&&f.route&&Array.isArray(f.roles)));
const robot=fs.readFileSync('js/baa-guide-robot.js','utf8');
const css=fs.readFileSync('css/baa-guide-robot.css','utf8');
assert.ok(robot.includes('BAAGuideRobot'));
assert.ok(robot.includes('baaGuideRobotButton'));
assert.ok(robot.includes('aria-expanded'));
assert.ok(robot.includes('Escape'));
assert.ok(robot.includes('/api/auth/me'));
assert.ok(robot.includes("credentials:'include'"),'Guide Robot role lookup must use the authenticated session');
assert.ok(robot.includes("cache:'no-store'"),'Guide Robot role lookup must not use a cached identity response');
assert.ok(!robot.includes("localStorage.getItem('baa.user')"),'Guide Robot must not trust localStorage for role visibility');
assert.ok(robot.includes('roleResolved'),'Guide Robot must wait for server role resolution before showing role-specific features');
assert.ok(robot.includes('roles.some'),'Guide Robot must allow any matching server-authoritative role');
assert.ok(robot.includes('getCurrentRoles'),'Guide Robot must expose the resolved role set without trusting browser storage');
assert.ok(robot.includes('currentPath()'),'Guide Robot must resolve the current route for contextual guidance');
assert.ok(robot.includes('contextual explanation'),'Guide Robot must identify the current feature context');
assert.ok(robot.includes('explain(here.id)'),'Guide Robot must surface contextual guidance for the current page');
assert.ok(robot.includes('id="baaGuideRobotAnswer" class="baa-guide-answer" tabindex="-1"'),'Guide Robot answer must be keyboard-focusable');
assert.ok(robot.includes('answer.focus();'),'Guide Robot must move focus to the rendered answer');
assert.ok(css.includes('.baa-guide-launcher'));
assert.ok(css.includes('@media(max-width:560px)'));
assert.ok(css.includes('prefers-reduced-motion'));
console.log('M63 PASS');