#!/usr/bin/env node
const fs=require('fs'),assert=require('assert'),vm=require('vm');
const c={window:{localStorage:{getItem:()=>null,setItem:()=>{},removeItem:()=>{},key:()=>null,length:0}}};
vm.createContext(c);
vm.runInContext(fs.readFileSync('js/baa-explainability.js','utf8'),c);
const api=c.window.BAAExplainability;
assert.ok(api);
assert.equal(api.MIN_EVIDENCE,3);
assert.equal(api.explain({evidenceCount:1,correctCount:1,state:'developing',source:'assessment'}).evidenceGate.sufficient,false);
assert.ok(api.explain({evidenceCount:2,state:'steady',source:'assessment'}).reasons.some(x=>x.includes('insufficient evidence')));
assert.ok(!api.explain({evidenceCount:2,state:'steady',source:'assessment'}).reasons.some(x=>x.includes('Current evidence state')));
assert.equal(api.explain({evidenceCount:3,correctCount:2,state:'steady',source:'assessment'}).evidenceGate.sufficient,true);
assert.ok(api.explain({evidenceCount:3,correctCount:2,state:'steady',source:'assessment'}).reasons.some(x=>x.includes('steady')));
assert.equal(api.explain({evidenceCount:'not-a-number'}).error,'INVALID_EVIDENCE_COUNT');
assert.equal(api.explain({correctCount:-1}).error,'INVALID_CORRECT_COUNT');
assert.equal(api.explain({evidenceCount:3,correctCount:4}).error,'INVALID_CORRECT_COUNT');
assert.equal(api.explain({evidenceCount:3,state:'made-up',source:'assessment'}).error,'INVALID_EXPLANATION_STATE');
assert.equal(api.explain({evidenceCount:3,state:'steady',source:'assessment feed'}).error,'INVALID_EXPLANATION_SOURCE');
assert.ok(api.explain({evidenceCount:3,state:'steady',source:'assessment'}).limitation.includes('stored evidence'));
console.log('M38 PASS');
