const assert=require('assert');
const fs=require('fs');
const vm=require('vm');
const storage=new Map();
const context={console,localStorage:{getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v)},window:{}};
vm.createContext(context);
vm.runInContext(fs.readFileSync('js/baa-billing.js','utf8'),context);
const b=context.window.BAABilling;
assert.strictEqual(b.plans().length,4);
assert.strictEqual(b.getState().planId,'free');
assert.strictEqual(b.subscribe('student').ok,true);
assert.strictEqual(b.getState().planId,'student');
assert.strictEqual(b.entitlement('Advanced analytics').allowed,true);
assert.strictEqual(b.subscribe('institution').ok,false);
assert.strictEqual(b.cancel().state.status,'cancelled');
console.log('Billing foundation tests: PASS');
