#!/usr/bin/env node
const fs=require('fs'),assert=require('assert'),vm=require('vm');
const c={window:{localStorage:{getItem:()=>null,setItem:()=>{},removeItem:()=>{},key:()=>null,length:0}}};
vm.createContext(c);
vm.runInContext(fs.readFileSync('js/baa-adaptive-pacing.js','utf8'),c);
const api=c.window.BAAPacing;
assert.ok(api);
assert.equal(api.recommend({availableMinutes:30,plannedMinutes:60,energyLevel:4}).action,'reduce_scope');
assert.equal(api.recommend({availableMinutes:60,plannedMinutes:30,energyLevel:2}).action,'reduce_intensity');
assert.equal(api.recommend({availableMinutes:90,plannedMinutes:30,energyLevel:4}).action,'optional_extension');
assert.equal(api.recommend({availableMinutes:30,plannedMinutes:30,energyLevel:4}).action,'maintain');
assert.equal(api.recommend({availableMinutes:30,plannedMinutes:30,energyLevel:6}).error,'INVALID_PACING_VALUES');
const endpoint=fs.readFileSync('api/m56-adaptive-pacing.js','utf8');
assert(endpoint.includes("req.method !== 'POST'"));
assert(endpoint.includes('requireAuth(req)'));
assert(endpoint.includes("Cache-Control', 'private, no-store, max-age=0"));
assert(endpoint.includes('INVALID_PACING_VALUES'));
const bridge=fs.readFileSync('js/baa-m56-adaptive-pacing-server.js','utf8');
assert(bridge.includes("credentials:'include'"));
assert(bridge.includes("cache:'no-store'"));
assert(bridge.includes("Accept':'application/json"));
assert(bridge.includes("/api/m56-adaptive-pacing"));
const catalogue=fs.readFileSync('js/baa-guide-catalogue.js','utf8');
assert(catalogue.includes("id:'adaptive-pacing'"));
assert(catalogue.includes("js/baa-m56-adaptive-pacing-server.js"));
console.log('M56 PASS — deterministic pacing rules, authenticated server contract, fresh client bridge, and Guide Robot/bootstrap reachability');
