#!/usr/bin/env node
const fs=require('fs'),assert=require('assert'),vm=require('vm');
const c={window:{localStorage:{getItem:()=>null,setItem:()=>{},removeItem:()=>{},key:()=>null,length:0}}};
vm.createContext(c);
vm.runInContext(fs.readFileSync('js/baa-parent-conversation.js','utf8'),c);
const api=c.window.BAAParentConversation;
assert.ok(api);
assert.equal(api.prompts({topic:'Algebra'}).prompts.length,4);
const endpoint=fs.readFileSync('api/m57-parent-conversation.js','utf8');
assert(endpoint.includes('parent_learner'));
assert(endpoint.includes("status='active'"));
assert(endpoint.includes('LEARNER_ACCESS_DENIED'));
assert(endpoint.includes('learning_evidence'));
assert(endpoint.includes('loadLearningContext'));
assert(endpoint.includes('evidenceCount'));
assert(endpoint.includes('const topic = context.topic'));
assert(endpoint.includes('const state = context.state'));
assert(!endpoint.includes('const requestedTopic = clean(req.body?.topic'));
assert(endpoint.includes("Cache-Control', 'private, no-store, max-age=0"));
assert(endpoint.includes('Conversation prompts are supportive guidance'));
assert(endpoint.includes('does not measure emotion or wellbeing'));
assert(endpoint.includes('writeAudit'));
const client=fs.readFileSync('js/baa-parent-conversation.js','utf8');
assert(client.includes("credentials:AUTH.credentials"));
assert(client.includes("cache:'no-store'"));
assert(client.includes('const body={learnerId:String(source.learnerId||\'\').trim()}'));
assert(!client.includes('topic:root.dataset.topic'));
console.log('M57 PASS — parent ownership, authenticated uncached client, server-derived learning context, and non-diagnostic contract');
