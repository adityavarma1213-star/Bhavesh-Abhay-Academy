-- ============================================================
-- 3. QUESTION BANK / ASSESSMENT CATALOG
--    (source: js/question-bank.js)
-- ============================================================

CREATE TABLE questions (
  id                TEXT PRIMARY KEY,       -- e.g. 'q_frac_001'
  subject           TEXT NOT NULL,
  chapter           TEXT NOT NULL,
  topic             TEXT NOT NULL,
  concept           TEXT NOT NULL,
  difficulty        TEXT NOT NULL,
  type              TEXT NOT NULL CHECK (type IN
                       ('mcq','true_false','short_answer','long_answer','math','step_based','written_response')),
  marks             NUMERIC NOT NULL,
  time_estimate_sec INTEGER,
  text              TEXT NOT NULL,
  options           JSONB,                  -- mcq/true_false option list
  correct_answer    TEXT,                   -- null for AI-graded-only questions without a single correct string
  model_answer      TEXT,
  explanation       TEXT,
  common_error_type TEXT,
  created_at        TIMESTAMPTZ NOT NULL,
  updated_at        TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_questions_concept ON questions(concept);
CREATE INDEX idx_questions_subject_chapter ON questions(subject, chapter);

CREATE TABLE assessments (
  id            TEXT PRIMARY KEY,           -- e.g. 'a_quick_fractions_quiz'
  title         TEXT NOT NULL,
  subject       TEXT,
  chapter       TEXT,
  total_marks   NUMERIC NOT NULL,
  created_at    TIMESTAMPTZ NOT NULL,
  updated_at    TIMESTAMPTZ NOT NULL
);

CREATE TABLE assessment_questions (
  assessment_id TEXT NOT NULL REFERENCES assessments(id) ON DELETE CASCADE,
  question_id   TEXT NOT NULL REFERENCES questions(id) ON DELETE RESTRICT,
  position      INTEGER NOT NULL,
  PRIMARY KEY (assessment_id, question_id)
);


-- ============================================================
-- 4. ASSESSMENT ATTEMPTS / ANSWERS / RESULTS
--    (source: js/baa-assessment.js — attempts/evidence/teacherReviews)
--    Every attempt is its own row. A new attempt NEVER overwrites
--    a prior one (attempt_number is a sequence, see SCHEMA.md §8).
-- ============================================================

CREATE TABLE assessment_attempts (
  id                TEXT PRIMARY KEY,       -- e.g. 'attempt_...'
  assessment_id     TEXT NOT NULL REFERENCES assessments(id) ON DELETE RESTRICT,
  learner_id        TEXT NOT NULL REFERENCES learners(id) ON DELETE CASCADE,
  attempt_number    INTEGER NOT NULL,       -- 1..n per (learner_id, assessment_id)
  start_time        TIMESTAMPTZ NOT NULL,
  end_time          TIMESTAMPTZ,
  status            TEXT NOT NULL DEFAULT 'in_progress'
                       CHECK (status IN ('in_progress','submitted','evaluated')),
  evaluation_status TEXT NOT NULL DEFAULT 'pending'
                       CHECK (evaluation_status IN ('pending','partial','complete','failed')),
  review_status     TEXT NOT NULL DEFAULT 'not_reviewed'
                       CHECK (review_status IN ('not_reviewed','pending_review','accepted','edited','rejected')),
  score             NUMERIC,
  max_score         NUMERIC,
  UNIQUE (learner_id, assessment_id, attempt_number)
);
CREATE INDEX idx_attempts_learner ON assessment_attempts(learner_id);
CREATE INDEX idx_attempts_assessment ON assessment_attempts(assessment_id);

-- Raw submitted answers, one per question per attempt (source data).
CREATE TABLE assessment_answers (
  id            TEXT PRIMARY KEY,
  attempt_id    TEXT NOT NULL REFERENCES assessment_attempts(id) ON DELETE CASCADE,
  question_id   TEXT NOT NULL REFERENCES questions(id) ON DELETE RESTRICT,
  raw_answer    TEXT,
  answered_at   TIMESTAMPTZ NOT NULL,
  UNIQUE (attempt_id, question_id)
);

-- Graded result per question per attempt (source data — this is the
-- durable record of what grade a question received and how).
CREATE TABLE assessment_results (
  id                    TEXT PRIMARY KEY,
  attempt_id            TEXT NOT NULL REFERENCES assessment_attempts(id) ON DELETE CASCADE,
  question_id           TEXT NOT NULL REFERENCES questions(id) ON DELETE RESTRICT,
  grading_mode          TEXT NOT NULL CHECK (grading_mode IN ('auto','ai')),
  is_correct            BOOLEAN,           -- auto-graded only; null for AI-graded (see correctness)
  correctness            TEXT,              -- 'correct'|'incorrect'|'partially_correct'|'uncertain'
  score                 NUMERIC,           -- null = evaluation failed, never fabricated
  max_score             NUMERIC NOT NULL,
  confidence            TEXT,              -- 'high'|'medium'|'low'|'human_review_required'
  human_review_required BOOLEAN NOT NULL DEFAULT FALSE,
  evaluation_failed      BOOLEAN NOT NULL DEFAULT FALSE,
  created_at            TIMESTAMPTZ NOT NULL,
  UNIQUE (attempt_id, question_id)
);
CREATE INDEX idx_results_attempt ON assessment_results(attempt_id);

-- AI evaluation is stored as its own record, separate from the teacher's
-- eventual decision (SCHEMA.md §13 / requirement 13: "AI evaluation is
-- not the teacher decision"). One row per AI grading call.
CREATE TABLE ai_evaluation_records (
  id                   TEXT PRIMARY KEY,
  attempt_id           TEXT NOT NULL REFERENCES assessment_attempts(id) ON DELETE CASCADE,
  question_id          TEXT NOT NULL REFERENCES questions(id) ON DELETE RESTRICT,
  model                TEXT,               -- e.g. 'gemini-3.5-flash-lite'
  score                NUMERIC,
  correctness           TEXT,
  explanation           TEXT,
  errors                JSONB,              -- array of tagged error strings
  missing_concepts       JSONB,
  suggested_improvement  TEXT,
  confidence            TEXT,
  human_review_required BOOLEAN NOT NULL DEFAULT FALSE,
  created_at            TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_ai_eval_attempt ON ai_evaluation_records(attempt_id);

-- Human review queue + decision. References the AI evaluation it is
-- reviewing but is its own row — accepting/editing/rejecting never
-- overwrites the AI evaluation record above.
CREATE TABLE teacher_reviews (
  id                    TEXT PRIMARY KEY,
  attempt_id            TEXT NOT NULL REFERENCES assessment_attempts(id) ON DELETE CASCADE,
  question_id           TEXT NOT NULL REFERENCES questions(id) ON DELETE RESTRICT,
  ai_evaluation_id      TEXT REFERENCES ai_evaluation_records(id) ON DELETE SET NULL,
  learner_id            TEXT NOT NULL REFERENCES learners(id) ON DELETE CASCADE,
  teacher_status        TEXT NOT NULL DEFAULT 'pending'
                           CHECK (teacher_status IN ('pending','accepted','edited','rejected')),
  teacher_marks         NUMERIC,
  teacher_comment        TEXT,
  reviewer_user_id       TEXT REFERENCES users(id) ON DELETE SET NULL,
  reviewed_at            TIMESTAMPTZ,
  created_at             TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_reviews_learner ON teacher_reviews(learner_id);
CREATE INDEX idx_reviews_status ON teacher_reviews(teacher_status);

-- Free-text teacher notes (source: teacher-os.html Section D notes store).
CREATE TABLE teacher_notes (
  id            TEXT PRIMARY KEY,
  learner_id    TEXT NOT NULL REFERENCES learners(id) ON DELETE CASCADE,
  author_user_id TEXT REFERENCES users(id) ON DELETE SET NULL,
  text          TEXT NOT NULL,
  created_at    TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_teacher_notes_learner ON teacher_notes(learner_id);


-- ============================================================
-- 5. LEARNING EVIDENCE / LEARNING MEMORY / MISTAKE PATTERNS
--    Evidence is SOURCE data. learning_memory is DERIVED/cacheable
--    (see SCHEMA.md §10) — it can always be recomputed from evidence.
-- ============================================================

CREATE TABLE learning_evidence (
  id            TEXT PRIMARY KEY,           -- e.g. 'ev_...'
  learner_id    TEXT NOT NULL REFERENCES learners(id) ON DELETE CASCADE,
  attempt_id    TEXT NOT NULL REFERENCES assessment_attempts(id) ON DELETE CASCADE,
  assessment_id TEXT NOT NULL REFERENCES assessments(id) ON DELETE RESTRICT,
  question_id   TEXT NOT NULL REFERENCES questions(id) ON DELETE RESTRICT,
  subject       TEXT NOT NULL,
  chapter       TEXT,
  topic         TEXT,
  concept       TEXT NOT NULL,
  difficulty    TEXT,
  correctness   TEXT NOT NULL,              -- 'correct'|'incorrect'|'partially_correct'|'uncertain'
  error_type    TEXT,
  score         NUMERIC,
  max_score     NUMERIC,
  confidence    TEXT,
  evidence_type TEXT NOT NULL DEFAULT 'assessment_answer', -- extensible: future evidence sources
  source        TEXT NOT NULL DEFAULT 'section_b_assessment',
  created_at    TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_evidence_learner ON learning_evidence(learner_id);
CREATE INDEX idx_evidence_learner_concept ON learning_evidence(learner_id, concept);
CREATE INDEX idx_evidence_attempt ON learning_evidence(attempt_id);

-- DERIVED. One row per (learner, concept). Recomputable from
-- learning_evidence at any time — see js/baa-assessment.js
-- updateLearningMemory() for the exact derivation rule being mirrored.
CREATE TABLE learning_memory (
  learner_id      TEXT NOT NULL REFERENCES learners(id) ON DELETE CASCADE,
  concept         TEXT NOT NULL,
  subject         TEXT,
  topic           TEXT,
  status          TEXT NOT NULL CHECK (status IN
                     ('insufficient_evidence','mastered','learning','needs_revision')),
  evidence_count  INTEGER NOT NULL DEFAULT 0,
  correct_count   INTEGER NOT NULL DEFAULT 0,
  last_updated    TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (learner_id, concept)
);

-- Append-only history of learning_memory transitions (bounded/rolled up
-- by the application layer, mirrors the in-memory `history` array today).
CREATE TABLE learning_memory_history (
  id            TEXT PRIMARY KEY,
  learner_id    TEXT NOT NULL REFERENCES learners(id) ON DELETE CASCADE,
  concept       TEXT NOT NULL,
  status        TEXT NOT NULL,
  evidence_count INTEGER NOT NULL,
  recorded_at   TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_memory_history_learner_concept ON learning_memory_history(learner_id, concept);

-- Mistake patterns are DERIVED but must stay explainable (requirement
-- 12), so every pattern links back to the individual evidence rows that
-- produced it via mistake_pattern_occurrences rather than only storing
-- an aggregate count.
CREATE TABLE mistake_patterns (
  id             TEXT PRIMARY KEY,          -- e.g. 'pattern_...'
  learner_id     TEXT NOT NULL REFERENCES learners(id) ON DELETE CASCADE,
  concept        TEXT NOT NULL,
  subject        TEXT,
  error_type     TEXT NOT NULL,
  status         TEXT NOT NULL DEFAULT 'watching' CHECK (status IN ('watching','possible_misconception')),
  first_detected TIMESTAMPTZ NOT NULL,
  last_detected  TIMESTAMPTZ NOT NULL,
  UNIQUE (learner_id, concept, error_type)
);
CREATE INDEX idx_mistake_patterns_learner ON mistake_patterns(learner_id);

CREATE TABLE mistake_pattern_occurrences (
  id            TEXT PRIMARY KEY,
  pattern_id    TEXT NOT NULL REFERENCES mistake_patterns(id) ON DELETE CASCADE,
  evidence_id   TEXT NOT NULL REFERENCES learning_evidence(id) ON DELETE CASCADE,
  occurred_at   TIMESTAMPTZ NOT NULL,
  UNIQUE (pattern_id, evidence_id)
);
CREATE INDEX idx_pattern_occurrences_pattern ON mistake_pattern_occurrences(pattern_id);


-- ============================================================
-- 6. PLANNER
--    (source: js/baa-planner.js)
-- ============================================================

CREATE TABLE planner_preferences (
  learner_id                TEXT PRIMARY KEY REFERENCES learners(id) ON DELETE CASCADE,
  available_minutes_per_day INTEGER NOT NULL DEFAULT 30,
  updated_at                TIMESTAMPTZ NOT NULL
);

CREATE TABLE planner_goals (
  id            TEXT PRIMARY KEY,
  learner_id    TEXT NOT NULL REFERENCES learners(id) ON DELETE CASCADE,
  text          TEXT NOT NULL,
  created_at    TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_planner_goals_learner ON planner_goals(learner_id);

CREATE TABLE planner_upcoming_assessments (
  id            TEXT PRIMARY KEY,
  learner_id    TEXT NOT NULL REFERENCES learners(id) ON DELETE CASCADE,
  title         TEXT NOT NULL,
  subject       TEXT,
  date          DATE NOT NULL,
  assessment_id TEXT REFERENCES assessments(id) ON DELETE SET NULL,
  created_at    TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_planner_upcoming_learner ON planner_upcoming_assessments(learner_id);

-- Tasks are never deleted on completion/miss — status transitions,
-- history preserved via planner_task_events (requirement 18/26).
CREATE TABLE planner_tasks (
  id                TEXT PRIMARY KEY,       -- e.g. 'task_...'
  learner_id        TEXT NOT NULL REFERENCES learners(id) ON DELETE CASCADE,
  type              TEXT NOT NULL,          -- e.g. 'practice' | 'revision' | 'reassessment'
  title             TEXT NOT NULL,
  concept           TEXT,
  subject           TEXT,
  estimated_minutes INTEGER NOT NULL,
  priority          TEXT NOT NULL,
  reasons           JSONB NOT NULL DEFAULT '[]', -- explainability: why this task was generated
  action            JSONB,                  -- e.g. { kind: 'assessment', assessmentId: ... }
  status            TEXT NOT NULL DEFAULT 'pending'
                       CHECK (status IN ('pending','completed','missed','cancelled','skipped')),
  scheduled_date    DATE NOT NULL,
  created_at        TIMESTAMPTZ NOT NULL,
  completed_at      TIMESTAMPTZ
);
CREATE INDEX idx_planner_tasks_learner ON planner_tasks(learner_id);
CREATE INDEX idx_planner_tasks_learner_date ON planner_tasks(learner_id, scheduled_date);

CREATE TABLE planner_task_events (
  id            TEXT PRIMARY KEY,
  task_id       TEXT NOT NULL REFERENCES planner_tasks(id) ON DELETE CASCADE,
  event         TEXT NOT NULL,              -- 'created' | 'missed' | 'cancelled' | 'completed' | ...
  note          TEXT,
  occurred_at   TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_planner_task_events_task ON planner_task_events(task_id);


