-- ============================================================
-- 1. IDENTITY / RELATIONSHIPS
--    (schema only — G1 does not implement auth/authorization;
--    see G2/G3. These tables exist so every other table has a
--    stable place to eventually attach a real account.)
-- ============================================================

CREATE TABLE users (
  id            TEXT PRIMARY KEY,          -- e.g. 'user_...'
  display_name  TEXT NOT NULL,
  email         TEXT UNIQUE,               -- nullable: G1 does not require an account to exist
  created_at    TIMESTAMPTZ NOT NULL,
  updated_at    TIMESTAMPTZ NOT NULL,
  deactivated_at TIMESTAMPTZ                -- soft-delete / lifecycle, see SCHEMA.md section 18
);

-- A user can hold more than one role (e.g. a teacher who is also a parent).
CREATE TABLE user_roles (
  user_id  TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role     TEXT NOT NULL CHECK (role IN ('student', 'parent', 'teacher', 'admin')),
  granted_at TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (user_id, role)
);


-- ============================================================
-- 1a. AUTHENTICATION (Section G2.1 — SCHEMA / DESIGN ONLY)
--    G1 defined `users` and `user_roles` as identity foundations
--    but deliberately implemented no authentication (see G1's
--    "what G1 does not do", and SCHEMA.md section 14). G1 also
--    never defined how a user's credential or a login session
--    would be stored — `credentials` and `auth_sessions` below
--    fill that specific, previously-undefined gap.
--
--    STATUS: exactly like every other table in this file, these
--    two tables are SCHEMA / MIGRATION DESIGN ONLY. No live
--    database is connected to this project (see file header).
--    Nothing in this codebase creates, reads, or writes to these
--    tables yet — no signup form, no login form, no session
--    issuance/verification code, no password hashing call. That
--    is out of scope for G2.1 and belongs to later G2 checkpoints
--    (client-side account creation/login, session-aware
--    repository wiring) and, for anything requiring a real,
--    network-verified secret, to G4 (secure API layer / backend
--    migration — see SCHEMA.md section 12, which explains why no
--    live database or provider exists yet).
-- ============================================================

-- One row per user's login credential. Only a password HASH is ever
-- stored — never a plaintext password (requirement carried over from
-- G1's privacy stance in SCHEMA.md section 9, applied here to auth
-- data). `algorithm` is recorded per-row so a future hashing-scheme
-- upgrade doesn't require guessing what produced an existing hash.
-- A user has at most one row here today (1:1 with `users`); modeled
-- as its own table rather than columns on `users` so `users` stays
-- a plain identity table and credential rotation/history can be
-- extended later without touching the identity schema G1 already
-- shipped.
CREATE TABLE credentials (
  user_id        TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  password_hash  TEXT NOT NULL,
  algorithm      TEXT NOT NULL DEFAULT 'argon2id', -- hashing scheme identifier, not chosen/implemented by G2.1
  created_at     TIMESTAMPTZ NOT NULL,
  updated_at     TIMESTAMPTZ NOT NULL
);

-- One row per active (or expired/revoked) login session. Sessions
-- are modeled as their own table, not a JWT-only/stateless scheme,
-- so a session can be looked up, listed, and revoked server-side —
-- matching this project's existing "never silently fabricate or
-- lose state" stance (see G1's soft-delete/lifecycle approach,
-- SCHEMA.md section 10). `token_hash` stores a hash of the session
-- token, never the raw token, mirroring the credentials table's
-- hash-only rule. `revoked_at` follows the same soft-delete pattern
-- G1 already uses elsewhere (`deactivated_at`, `archived_at`, etc.)
-- rather than deleting session rows outright.
CREATE TABLE auth_sessions (
  id            TEXT PRIMARY KEY,          -- e.g. 'session_...'
  user_id       TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash    TEXT NOT NULL UNIQUE,
  created_at    TIMESTAMPTZ NOT NULL,
  expires_at    TIMESTAMPTZ NOT NULL,
  revoked_at    TIMESTAMPTZ
);
CREATE INDEX idx_auth_sessions_user ON auth_sessions(user_id);


-- A learner is the "student" identity that owns learning data. It is
-- modeled separately from `users` because Section A/B/C/D currently
-- identify a student purely by a display name in localStorage, with
-- no account at all — a learner record must be able to exist before
-- (or without) a login. `user_id` is nullable and is filled in once
-- G2 (auth) links a real account to the learner.
CREATE TABLE learners (
  id            TEXT PRIMARY KEY,          -- e.g. 'learner_...'
  user_id       TEXT REFERENCES users(id) ON DELETE SET NULL,
  display_name  TEXT NOT NULL,             -- maps to today's `baa_student_name`
  created_at    TIMESTAMPTZ NOT NULL,
  updated_at    TIMESTAMPTZ NOT NULL,
  deactivated_at TIMESTAMPTZ
);

CREATE TABLE parent_learner (
  id            TEXT PRIMARY KEY,
  parent_user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  learner_id    TEXT NOT NULL REFERENCES learners(id) ON DELETE CASCADE,
  relationship  TEXT NOT NULL DEFAULT 'parent', -- 'parent' | 'guardian' | 'other_authorized_adult'
  status        TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'revoked')),
  created_at    TIMESTAMPTZ NOT NULL,
  revoked_at    TIMESTAMPTZ,
  UNIQUE (parent_user_id, learner_id)
);

CREATE TABLE teacher_learner (
  id            TEXT PRIMARY KEY,
  teacher_user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  learner_id    TEXT NOT NULL REFERENCES learners(id) ON DELETE CASCADE,
  status        TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'revoked')),
  created_at    TIMESTAMPTZ NOT NULL,
  revoked_at    TIMESTAMPTZ,
  UNIQUE (teacher_user_id, learner_id)
);

CREATE TABLE classes (
  id            TEXT PRIMARY KEY,
  teacher_user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name          TEXT NOT NULL,
  subject       TEXT,
  created_at    TIMESTAMPTZ NOT NULL,
  updated_at    TIMESTAMPTZ NOT NULL,
  archived_at   TIMESTAMPTZ
);

CREATE TABLE class_members (
  id            TEXT PRIMARY KEY,
  class_id      TEXT NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
  learner_id    TEXT NOT NULL REFERENCES learners(id) ON DELETE CASCADE,
  status        TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'removed')),
  joined_at     TIMESTAMPTZ NOT NULL,
  removed_at    TIMESTAMPTZ,
  UNIQUE (class_id, learner_id)
);


